-- Utsav Ethnic Studio catalogue setup
-- Run this entire script in Supabase > SQL Editor > New query.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Other',
  price numeric(12,2),
  description text not null default '',
  image_url text not null default '',
  image_path text not null default '',
  featured boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.products enable row level security;
drop policy if exists "Public can view products" on public.products;
create policy "Public can view products" on public.products for select using (true);
drop policy if exists "Signed-in admins can insert products" on public.products;
create policy "Signed-in admins can insert products" on public.products for insert to authenticated with check (true);
drop policy if exists "Signed-in admins can update products" on public.products;
create policy "Signed-in admins can update products" on public.products for update to authenticated using (true) with check (true);
drop policy if exists "Signed-in admins can delete products" on public.products;
create policy "Signed-in admins can delete products" on public.products for delete to authenticated using (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-photos', 'product-photos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Public can view product photos" on storage.objects;
create policy "Public can view product photos" on storage.objects for select using (bucket_id = 'product-photos');
drop policy if exists "Signed-in admins can upload product photos" on storage.objects;
create policy "Signed-in admins can upload product photos" on storage.objects for insert to authenticated with check (bucket_id = 'product-photos');
drop policy if exists "Signed-in admins can update product photos" on storage.objects;
create policy "Signed-in admins can update product photos" on storage.objects for update to authenticated using (bucket_id = 'product-photos') with check (bucket_id = 'product-photos');
drop policy if exists "Signed-in admins can delete product photos" on storage.objects;
create policy "Signed-in admins can delete product photos" on storage.objects for delete to authenticated using (bucket_id = 'product-photos');

